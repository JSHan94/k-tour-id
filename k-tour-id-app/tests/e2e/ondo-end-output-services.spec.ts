for (const viewport of [{ width: 320, height: 460 }, { width: 844, height: 390 }]) {
  test(`public task footers stay reachable in a short viewport ${viewport.width}x${viewport.height}`, async ({ page }, testInfo) => {
    test.setTimeout(60_000)
    await start(page, 390, true)
    await openReservation(page)
    await page.setViewportSize(viewport)
    const submit = page.getByTestId("reservation-submit")
    await expect(submit).toBeInViewport()
    await submit.click()
    await expect(page.getByTestId("reservation-sample")).toHaveAttribute("data-phase", "confirmed")
    const cancel = page.getByTestId("reservation-cancel")
    await expect(cancel).toBeInViewport()
    const summary = page.getByTestId("reservation-sample").locator("details > summary")
    await summary.scrollIntoViewIfNeeded()
    const summaryBox = await summary.boundingBox()
    const doneBox = await page.getByRole("button", { name: "Done", exact: true }).boundingBox()
    expect(summaryBox!.y + summaryBox!.height).toBeLessThanOrEqual(doneBox!.y + 1)
    await cancel.click()
    await expect(page.getByTestId("reservation-confirm-cancel")).toBeInViewport()
    await page.screenshot({ path: testInfo.outputPath(`reservation-short-${viewport.width}.png`) })
    await page.getByTestId("reservation-confirm-cancel").click()
    await expect(page.getByTestId("reservation-sample")).toHaveAttribute("data-phase", "cancelled")
    await page.keyboard.press("Escape")
    await expect(page.getByTestId("tables-reservation-open")).toBeFocused()
    await page.getByTestId("nav-settings").click()
    await page.getByTestId("ondo-b-device-data-settings").click()
    await page.getByTestId("account-services-open").click()
    await page.getByTestId("account-services-delete").click()
    await expect(page.getByTestId("account-services-submit")).toBeInViewport()
    expect(await page.locator("html").evaluate(node => node.scrollWidth <= node.clientWidth + 1)).toBe(true)
    await page.screenshot({ path: testInfo.outputPath(`account-short-${viewport.width}.png`) })
  })
}
