async function openTools(page: Page) {
  await page.locator('[data-testid="review-sample-indicator"]:visible').click()
  await page.getByTestId("integration-demo-open").click()
  await expect(page.getByTestId("integration-demo")).toBeVisible()
  await preparePartnerDevice(page)
}
async function chooseCase(page: Page, value: string) {
  const select = page.getByTestId("integration-verifier-case")
  const details = select.locator("..")
  if ((await details.getAttribute("open")) === null) await details.locator("summary").click()
  await select.selectOption(value)
}
async function check(page: Page, consent = true) {
  await runPartnerCheck(page, consent)
}

test("public partner mock covers consent, binding failures and one-event retry with no injected credentials", async ({ page, baseURL }) => {
  test.setTimeout(100_000)
  await page.setViewportSize({ width: 390, height: 844 })
  const errors: string[] = []
  page.on("pageerror", error => errors.push(error.message))
  await page.goto(`${baseURL}/`, { waitUntil: "domcontentloaded" })
  await page.getByTestId("onboarding-guest-skip").click()
  await page.getByTestId("nav-id").click()
  await page.getByTestId("kpass-sample-picker").click()
  await page.getByTestId("kpass-scenario-adult_visitor").click()
  await expect(page.getByTestId("kpass-scenario-adult_visitor")).toHaveCount(0)
  await openTools(page)
  for (const [scenario, status] of [["normal", "allowed"], ["wrong_audience", "denied"], ["replay", "denied"], ["expired", "expired"], ["revoked", "denied"]] as const) {
    await chooseCase(page, scenario)
    await check(page)
    await expect(page.getByTestId("integration-verifier-result")).toHaveAttribute("data-status", status)
    await page.screenshot({ path: test.info().outputPath(`verifier-${scenario}-390.png`) })
  }
  await chooseCase(page, "normal")
  await check(page, false)
  await expect(page.getByTestId("integration-verifier-result")).toContainText("Not shared")
  await page.getByTestId("integration-tab-events").click()
  await expect(page.getByTestId("integration-event")).toHaveCount(1)
  await page.getByTestId("integration-voucher-issue").click()
  await expect(page.getByTestId("integration-event")).toHaveCount(2)
  const outcome = page.getByTestId("integration-event-case")
  await outcome.locator("..").locator("summary").click()
  await outcome.selectOption("failure")
  await page.getByTestId("integration-event-KPassIssued").click()
  const issue = page.getByTestId("integration-event").filter({ hasText: "KPassIssued" })
  await expect(issue).toHaveAttribute("data-event-state", "failed")
  await page.getByTestId("integration-event-KPassIssued").click()
  await expect(issue).toHaveAttribute("data-event-state", "recorded")
  await expect(page.getByTestId("integration-event")).toHaveCount(2)
  await page.screenshot({ path: test.info().outputPath("events-390-light.png") })
  await page.getByRole("dialog", { name: "Partner tools", exact: true }).getByRole("button", { name: "Close", exact: true }).click()
  await expect(page.getByTestId("kpass-service-age")).toHaveAttribute("data-status", "allowed")
  await page.getByTestId("nav-settings").click()
  await page.getByTestId("settings-appearance-row").click()
  await page.getByTestId("settings-appearance-dark").click()
  await page.getByRole("dialog", { name: "Appearance", exact: true }).getByRole("button", { name: "Close", exact: true }).click()
  await page.getByTestId("nav-id").click()
  await openTools(page)
  await expect(page.getByTestId("integration-event")).toHaveCount(2)
  for (const width of [320, 390, 1280]) {
    await page.setViewportSize({ width, height: width === 320 ? 720 : 900 })
    const sheet = page.getByRole("dialog", { name: "Partner tools", exact: true })
    expect(await sheet.evaluate(node => node.scrollWidth <= node.clientWidth + 1)).toBe(true)
    for (const button of await sheet.locator("button:visible, summary:visible").all()) expect((await button.boundingBox())!.height).toBeGreaterThanOrEqual(43.99)
    await page.screenshot({ path: test.info().outputPath(`events-${width}-dark.png`) })
  }
  expect(errors).toEqual([])
})

