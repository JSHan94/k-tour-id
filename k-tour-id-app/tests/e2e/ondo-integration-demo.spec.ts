test("public receipt retains its checked time but becomes stale after revocation and while open at expiry", async ({ page, baseURL }) => {
  test.setTimeout(70_000)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.clock.install()
  await page.goto(`${baseURL}/`, { waitUntil: "domcontentloaded" })
  await page.getByTestId("onboarding-guest-skip").click()
  await page.getByTestId("nav-id").click()
  await page.getByTestId("kpass-sample-picker").click()
  await page.getByTestId("kpass-scenario-adult_visitor").click()
  await expect(page.getByTestId("kpass-scenario-adult_visitor")).toHaveCount(0)
  await openTools(page)
  await check(page)
  const result = page.getByTestId("integration-verifier-result")
  await expect(result).toHaveAttribute("data-status", "allowed")
  const checkedAt = await page.getByTestId("integration-receipt-checked-at").getAttribute("datetime")
  await page.getByRole("dialog", { name: "Partner tools", exact: true }).getByRole("button", { name: "Close", exact: true }).click()
  await page.getByTestId("kpass-sample-picker").click()
  await page.getByTestId("kpass-scenario-revoked").click()
  await expect(page.getByTestId("kpass-scenario-revoked")).toHaveCount(0)
  await openTools(page)
  await expect(result).toHaveAttribute("data-status", "stale")
  await expect(result).toHaveAttribute("data-receipt-decision", "allowed")
  await expect(result).toHaveAttribute("data-receipt-current", "false")
  await expect(result.getByRole("heading")).toHaveText("Check again")
  await expect(page.getByTestId("integration-receipt-checked-at")).toHaveAttribute("datetime", checkedAt!)
  await page.screenshot({ path: test.info().outputPath("receipt-revoked-stale-390.png") })
  await page.getByRole("dialog", { name: "Partner tools", exact: true }).getByRole("button", { name: "Close", exact: true }).click()
  await page.getByTestId("kpass-sample-picker").click()
  await page.getByTestId("kpass-scenario-adult_visitor").click()
  await expect(page.getByTestId("kpass-scenario-adult_visitor")).toHaveCount(0)
  await openTools(page)
  await check(page)
  await expect(result).toHaveAttribute("data-status", "allowed")
  // Only the browser clock advances; credentials still come from the public
  // sample picker, and the UI's own deadline callback must invalidate it.
  await page.clock.fastForward(121_000)
  await expect(result).toHaveAttribute("data-status", "stale")
  await expect(result.getByRole("heading")).toHaveText("Check again")
  await page.screenshot({ path: test.info().outputPath("receipt-clock-stale-390.png") })
})

